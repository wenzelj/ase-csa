"""Durable connected-device register for a CSA project.

``hosts.csv`` and ``addresses.csv`` are regenerated by ``hostmodel`` on every
rebuild, so an assessor's identification of an IP or name as a particular
device would be lost. This store keeps those decisions project-locally and
independently of rebuilds, in three files under ``<work_dir>/hosts/``:

* ``connected_devices.csv``  one durable row per identified device (stable ID,
                            name, type, role, owner, site/zone, relationship,
                            classification, identification state, provenance,
                            reviewer, active, revision).
* ``device_addresses.csv``   one row per alias of a device (normalised IP or
                            FQDN, type, first/last seen, source, active).
* ``device-audit.jsonl``     append-only create/update/retire/restore events
                            with before/after records.

A reviewed ``hosts/endpoints.csv`` label can be brought in with ``import_endpoints_plan`` (a
read-only dry run that lists what would be created and what needs a person) and
``import_endpoints_apply`` (explicit, idempotent). Imported devices are ``proposed``, never
``confirmed``; ``endpoints.csv`` itself is only read.

A fourth, separate input records the rare decision that a device is in fact an application host:

* ``host_scope.csv``        one row per conversion decision (stable ID, device, host name, the
                            addresses it takes, source, operator, date, active). ``hostmodel.build``
                            reads the active rows and registers the host as in scope on the next
                            rebuild. Creating, editing or confirming a device never writes it: only
                            ``convert_to_host``, after a read-only ``scope_plan`` whose ``preview_id``
                            the caller hands back, and ``reverse_conversion`` undoes it.

Retiring a device or an alias only turns off this register's decision; capture
observations, evidence-matrix rows and graph history are left untouched.
Standard library only. Writes take an exclusive project lock, write atomically
with a timestamped backup of the previous file, and append an audit event.
"""

from __future__ import annotations

import argparse
import csv
import datetime as dt
import fcntl
import ipaddress
import json
import os
import re
import shutil
import sys
from pathlib import Path

from csa_docx import tools

#: durable fields of a connected_devices.csv row, in file order
DEVICE_FIELDS = [
    "device_id", "name", "device_type", "role", "owner", "site_zone",
    "relationship", "classification", "identification_state", "provenance",
    "reviewer", "recorded", "active", "revision",
]
#: durable fields of a device_addresses.csv row, in file order
ADDRESS_FIELDS = [
    "device_id", "address", "normalized", "address_type", "first_seen",
    "last_seen", "source", "active",
]
DEVICE_ID = re.compile(r"^CD-\d{6}$")
CLASSIFICATIONS = {"supporting IT", "shared", "platform", "OT", "external", "unknown", "unclassified"}
ID_STATES = {"unidentified", "proposed", "confirmed", "disputed"}
ADDRESS_TYPES = {"ipv4", "ipv6", "fqdn"}
MAX_FIELD = 1500
#: fields an edit may change without moving the device off the register
EDITABLE_FIELDS = {
    "name", "device_type", "role", "owner", "site_zone", "relationship",
    "classification", "identification_state", "provenance", "reviewer",
}
ACTIVE = {"active": "true", "retired": "false"}
#: durable fields of a host_scope.csv row, in file order
SCOPE_FIELDS = [
    "decision_id", "device_id", "host", "ips", "system", "role", "site", "source", "operator",
    "decided", "active", "reversed_on", "reversed_by", "reverse_reason",
]
SCOPE_ID = re.compile(r"^HS-\d{6}$")
HOST_NAME = re.compile(r"^[A-Za-z][A-Za-z0-9-]{2,30}$")     # the same shape hostmodel accepts for a host name


def _utc() -> str:
    return dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")


def _error(message: str) -> dict:
    return {"status": "ERROR", "message": message}


def _ok(**kwargs) -> dict:
    out = {"status": "OK"}
    out.update(kwargs)
    return out


def _blocked(message: str) -> dict:
    return {"status": "BLOCKED", "message": message}


def _project(workspace: str | Path) -> Path:
    """Resolve and validate the workspace: it must be a registered project root."""
    value = Path(workspace).expanduser().resolve()
    guard = tools._check_workspace_registered(value)
    if guard:
        raise ValueError(guard["message"])
    if not value.is_dir():
        raise ValueError(f"project path does not exist: {value}")
    return value


def _work_dir(project: Path) -> Path:
    return project / "csa-work"


def _device_file(project: Path) -> Path:
    return _work_dir(project) / "hosts" / "connected_devices.csv"


def _address_file(project: Path) -> Path:
    return _work_dir(project) / "hosts" / "device_addresses.csv"


def _audit_file(project: Path) -> Path:
    return _work_dir(project) / "hosts" / "device-audit.jsonl"


def _scope_file(project: Path) -> Path:
    return _work_dir(project) / "hosts" / "host_scope.csv"


def _lock_file(project: Path) -> Path:
    return _work_dir(project) / "hosts" / ".connected-devices.lock"


def _normalize_address(value: str) -> str:
    """Normalise an IP or FQDN alias to its canonical lowercase form."""
    text = str(value or "").strip().lower()
    if not text:
        raise ValueError("address is required")
    if text.endswith("."):
        text = text[:-1]
    try:
        return str(ipaddress.ip_address(text))
    except ValueError:
        pass
    if not re.fullmatch(r"(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z][a-z0-9-]{1,61}[a-z0-9]", text):
        raise ValueError(f"not a valid IP address or FQDN: {value!r}")
    return text


def _address_type(normalized: str) -> str:
    try:
        ip = ipaddress.ip_address(normalized)
    except ValueError:
        return "fqdn"
    return "ipv4" if ip.version == 4 else "ipv6"


def _check_length(name: str, value: str) -> str:
    text = str(value or "").strip()
    if len(text) > MAX_FIELD:
        raise ValueError(f"{name} is too long ({len(text)} chars; keep <= {MAX_FIELD})")
    return text


def _read_csv(path: Path) -> list[dict]:
    if not path.is_file():
        return []
    with path.open(newline="", encoding="utf-8-sig") as fh:
        reader = csv.DictReader(fh)
        fields = reader.fieldnames or []
        return [{k: (v or "") for k, v in row.items() if k in fields} for row in reader]


def _active_devices(rows: list[dict]) -> dict[str, dict]:
    return {r["device_id"]: r for r in rows if r.get("active") == "true"}


def _active_alias_map(rows: list[dict]) -> dict[str, str]:
    """normalized active alias -> device_id (a duplicate would already have been rejected)."""
    return {r["normalized"]: r["device_id"] for r in rows if r.get("active") == "true"}


def _append_audit(project: Path, action: str, device_id: str, before: dict | None, after: dict | None,
                  addresses_before: list[dict] | None = None,
                  addresses_after: list[dict] | None = None) -> None:
    event = {
        "ts": _utc(),
        "action": action,
        "device_id": device_id,
        "before": before,
        "after": after,
        "addresses_before": addresses_before,
        "addresses_after": addresses_after,
    }
    path = _audit_file(project)
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = (json.dumps(event, ensure_ascii=False, sort_keys=True) + "\n").encode("utf-8")
    with path.open("ab") as fh:
        fh.write(payload)
        fh.flush()
        os.fsync(fh.fileno())


def _atomic_write(path: Path, data: bytes) -> None:
    """Write atomically (temp file + rename), keeping one timestamped backup of the previous file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.is_file():
        stamp = dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
        backup = path.with_name(f"{path.name}.bak-{stamp}")
        # an interrupted run may have left a backup at the same stamp; never clobber one
        counter = 1
        while backup.exists():
            backup = path.with_name(f"{path.name}.bak-{stamp}-{counter}")
            counter += 1
        shutil.copy2(path, backup)
    tmp = path.with_name(path.name + f".tmp-{os.getpid()}-{dt.datetime.now().microsecond}")
    with tmp.open("wb") as fh:
        fh.write(data)
        fh.flush()
        os.fsync(fh.fileno())
    os.replace(tmp, path)


def _write_csv(path: Path, fields: list[str], rows: list[dict]) -> None:
    import io
    buf = io.StringIO()
    writer = csv.DictWriter(buf, fieldnames=fields, extrasaction="ignore")
    writer.writeheader()
    for row in rows:
        writer.writerow(row)
    _atomic_write(path, buf.getvalue().encode("utf-8"))


def _next_device_id(rows: list[dict]) -> str:
    top = 0
    for row in rows:
        m = DEVICE_ID.fullmatch(str(row.get("device_id", "")))
        if m:
            top = max(top, int(m.group(0)[3:]))
    return f"CD-{top + 1:06d}"


def _validate_device_fields(values: dict, existing_id: str | None = None) -> dict:
    out = {f: _check_length(f, str(values.get(f) or "")) for f in DEVICE_FIELDS}
    out["device_id"] = existing_id or ""
    if not out.get("name"):
        raise ValueError("name is required")
    cls = out.get("classification") or "unknown"
    if cls not in CLASSIFICATIONS:
        raise ValueError(f"classification must be one of {sorted(CLASSIFICATIONS)}")
    state = out.get("identification_state") or "unidentified"
    if state not in ID_STATES:
        raise ValueError(f"identification_state must be one of {sorted(ID_STATES)}")
    if state == "confirmed" and not out.get("provenance"):
        raise ValueError("a confirmed device needs a provenance (basis or source reference)")
    out["classification"] = cls
    out["identification_state"] = state
    return out


def _validate_address(address: str, device_id: str, active_rows: list[dict]) -> dict:
    normalized = _normalize_address(address)
    clash = _active_alias_map(active_rows).get(normalized)
    if clash and clash != device_id:
        raise ValueError(f"address {normalized!r} is already an active alias of {clash}")
    return {
        "device_id": device_id,
        "address": _check_length("address", str(address).strip()),
        "normalized": normalized,
        "address_type": _address_type(normalized),
        "first_seen": _check_length("first_seen", ""),
        "last_seen": _check_length("last_seen", ""),
        "source": _check_length("source", ""),
        "active": "true",
    }


def _lock(project: Path):
    lock_path = _lock_file(project)
    lock_path.parent.mkdir(parents=True, exist_ok=True)
    fh = lock_path.open("a", encoding="utf-8")
    fcntl.flock(fh, fcntl.LOCK_EX)
    return fh


def _unlock(fh) -> None:
    try:
        fcntl.flock(fh, fcntl.LOCK_UN)
    finally:
        fh.close()


def _device_rows(project: Path) -> list[dict]:
    rows = _read_csv(_device_file(project))
    for row in rows:
        if not DEVICE_ID.fullmatch(str(row.get("device_id", ""))):
            raise ValueError(f"malformed device store: bad device_id {row.get('device_id')!r}")
        if row.get("active") not in ACTIVE.values():
            raise ValueError(f"malformed device store: bad active flag on {row.get('device_id')!r}")
    return rows


def _address_rows(project: Path) -> list[dict]:
    rows = _read_csv(_address_file(project))
    for row in rows:
        if not row.get("normalized"):
            raise ValueError(f"malformed address store: missing normalized alias for {row.get('device_id')!r}")
    return rows


def _get_device(project: Path, rows: list[dict], device_id: str, active_only: bool = True) -> dict:
    for row in rows:
        if row.get("device_id") == device_id:
            if active_only and row.get("active") != "true":
                raise ValueError(f"device {device_id} is retired; restore it first")
            return row
    raise ValueError(f"unknown device: {device_id}")


def create_device(project: str | Path, *, name: str, values: dict | None = None,
                  reviewer: str = "", addresses: list[str] | None = None) -> dict:
    """Create a connected-device register row, optionally with initial aliases."""
    project = _project(project)
    values = dict(values or {})
    values.setdefault("name", name)
    values.setdefault("recorded", _utc())
    values["reviewer"] = reviewer or values.get("reviewer", "")
    base = _validate_device_fields(values)
    lock = _lock(project)
    try:
        rows = _device_rows(project)
        araws = _address_rows(project)
        new = dict(base)
        new["device_id"] = _next_device_id(rows)
        new["active"] = "true"
        new["revision"] = "1"
        if not reviewer:
            new["recorded"] = new.get("recorded") or _utc()
        addresses_out = []
        if addresses:
            for addr in addresses:
                rec = _validate_address(addr, new["device_id"], araws)
                for prior in araws:
                    if prior.get("normalized") == rec["normalized"] and prior.get("active") == "true" and \
                            prior.get("device_id") == new["device_id"]:
                        raise ValueError("address already attached to this device")
                araws.append(rec)
                addresses_out.append(rec)
        rows.append(new)
        _write_csv(_device_file(project), DEVICE_FIELDS, rows)
        _write_csv(_address_file(project), ADDRESS_FIELDS, araws)
        _append_audit(project, "create", new["device_id"], None, new,
                      addresses_before=None, addresses_after=addresses_out)
        return _ok(device_id=new["device_id"], revision="1",
                   addresses=[a["normalized"] for a in addresses_out])
    finally:
        _unlock(lock)


def edit_device(project: str | Path, device_id: str, *, changes: dict, expected_revision: str | int | None = None) -> dict:
    """Edit a device's fields. Only EDITABLE_FIELDS may change; every edit bumps the revision."""
    project = _project(project)
    if not isinstance(changes, dict) or not changes:
        raise ValueError("changes must be a non-empty object")
    bad = set(changes) - EDITABLE_FIELDS
    if bad:
        raise ValueError(f"fields not editable: {sorted(bad)}")
    for key, value in changes.items():
        if not isinstance(value, str):
            raise ValueError(f"{key} must be a string")
    lock = _lock(project)
    try:
        rows = _device_rows(project)
        device = _get_device(project, rows, device_id)
        if expected_revision is not None and str(device.get("revision")) != str(expected_revision):
            raise ValueError(
                f"stale revision: expected {expected_revision}, current {device.get('revision')}")
        before = dict(device)
        merged = dict(before)
        for key, value in changes.items():
            merged[key] = _check_length(key, str(value))
        cls = merged.get("classification") or "unknown"
        if cls not in CLASSIFICATIONS:
            raise ValueError(f"classification must be one of {sorted(CLASSIFICATIONS)}")
        state = merged.get("identification_state") or "unidentified"
        if state not in ID_STATES:
            raise ValueError(f"identification_state must be one of {sorted(ID_STATES)}")
        if state == "confirmed" and not merged.get("provenance"):
            raise ValueError("a confirmed device needs a provenance (basis or source reference)")
        merged["revision"] = str(int(device.get("revision", "0")) + 1)
        rows[rows.index(device)] = merged
        _write_csv(_device_file(project), DEVICE_FIELDS, rows)
        _append_audit(project, "edit", device_id, before, merged)
        return _ok(device_id=device_id, before=before, after=merged)
    finally:
        _unlock(lock)


def add_address(project: str | Path, device_id: str, address: str, *, source: str = "",
                first_seen: str = "", last_seen: str = "") -> dict:
    project = _project(project)
    lock = _lock(project)
    try:
        rows = _device_rows(project)
        device = _get_device(project, rows, device_id)
        araws = _address_rows(project)
        rec = _validate_address(address, device_id, araws)
        if first_seen:
            rec["first_seen"] = _check_length("first_seen", first_seen)
        if last_seen:
            rec["last_seen"] = _check_length("last_seen", last_seen)
        if source:
            rec["source"] = _check_length("source", source)
        before = [dict(r) for r in araws if r.get("device_id") == device_id]
        araws.append(rec)
        _write_csv(_address_file(project), ADDRESS_FIELDS, araws)
        _append_audit(project, "add_address", device_id, None, rec,
                      addresses_before=before,
                      addresses_after=before + [rec])
        return _ok(device_id=device_id, address=rec)
    finally:
        _unlock(lock)


def remove_address(project: str | Path, device_id: str, address: str) -> dict:
    """Retire an alias: its row stays (active=false) so the decision history is kept."""
    project = _project(project)
    normalized = _normalize_address(address)
    lock = _lock(project)
    try:
        rows = _device_rows(project)
        _get_device(project, rows, device_id)
        araws = _address_rows(project)
        target = None
        for row in araws:
            if row.get("device_id") == device_id and row.get("normalized") == normalized:
                target = row
                break
        if target is None:
            raise ValueError(f"address {normalized!r} is not attached to {device_id}")
        if target.get("active") == "false":
            return _ok(device_id=device_id, address=target, already_retired=True)
        before = dict(target)
        target["active"] = "false"
        _write_csv(_address_file(project), ADDRESS_FIELDS, araws)
        _append_audit(project, "remove_address", device_id, before, dict(target))
        return _ok(device_id=device_id, address=target)
    finally:
        _unlock(lock)


def retire_device(project: str | Path, device_id: str, *, reviewer: str = "") -> dict:
    """Retire a device. Its rows and aliases stay (active=false); capture observations,
    evidence-matrix rows and graph history are never touched by this store."""
    project = _project(project)
    lock = _lock(project)
    try:
        rows = _device_rows(project)
        device = _get_device(project, rows, device_id)
        before = dict(device)
        device["active"] = "false"
        if reviewer:
            device["reviewer"] = _check_length("reviewer", reviewer)
        device["revision"] = str(int(device.get("revision", "0")) + 1)
        araws = _address_rows(project)
        for row in araws:
            if row.get("device_id") == device_id and row.get("active") == "true":
                row["active"] = "false"
        _write_csv(_device_file(project), DEVICE_FIELDS, rows)
        _write_csv(_address_file(project), ADDRESS_FIELDS, araws)
        _append_audit(project, "retire", device_id, before, dict(device))
        return _ok(device_id=device_id, before=before, after=dict(device))
    finally:
        _unlock(lock)


def restore_device(project: str | Path, device_id: str, *, reviewer: str = "") -> dict:
    project = _project(project)
    lock = _lock(project)
    try:
        rows = _device_rows(project)
        device = None
        for row in rows:
            if row.get("device_id") == device_id:
                device = row
                break
        if device is None:
            raise ValueError(f"unknown device: {device_id}")
        if device.get("active") == "true":
            return _ok(device_id=device_id, after=dict(device), already_active=True)
        before = dict(device)
        device["active"] = "true"
        if reviewer:
            device["reviewer"] = _check_length("reviewer", reviewer)
        device["revision"] = str(int(device.get("revision", "0")) + 1)
        _write_csv(_device_file(project), DEVICE_FIELDS, rows)
        _append_audit(project, "restore", device_id, before, dict(device))
        return _ok(device_id=device_id, before=before, after=dict(device))
    finally:
        _unlock(lock)


def list_devices(project: str | Path, *, include_retired: bool = True) -> list[dict]:
    project = _project(project)
    rows = _device_rows(project)
    if not include_retired:
        rows = [r for r in rows if r.get("active") == "true"]
    return rows


def get_device(project: str | Path, device_id: str, *, include_retired: bool = False) -> dict:
    project = _project(project)
    rows = _device_rows(project)
    if not include_retired:
        rows = [r for r in rows if r.get("active") == "true"]
    for row in rows:
        if row.get("device_id") == device_id:
            return row
    raise ValueError(f"unknown device: {device_id}")


def list_addresses(project: str | Path, device_id: str | None = None, *, include_retired: bool = True) -> list[dict]:
    project = _project(project)
    rows = _address_rows(project)
    if device_id:
        rows = [r for r in rows if r.get("device_id") == device_id]
    if not include_retired:
        rows = [r for r in rows if r.get("active") == "true"]
    return rows


def read_audit(project: str | Path, limit: int | None = None) -> list[dict]:
    """Read the append-only audit log, newest last. Corrupt lines are reported, not raised."""
    project = _project(project)
    path = _audit_file(project)
    out: list[dict] = []
    errors: list[dict] = []
    if path.is_file():
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            if not line.strip():
                continue
            try:
                out.append(json.loads(line))
            except ValueError as exc:
                errors.append({"line": number, "error": str(exc)})
    if limit is not None:
        out = out[-limit:]
    result = {"events": out, "errors": errors}
    if errors:
        result["status"] = "WARNING"
    return result


def resolve(project: str | Path, address: str) -> dict | None:
    """Resolve an alias (IP/FQDN) to the active device that owns it, or None."""
    project = _project(project)
    normalized = _normalize_address(address)
    for row in _address_rows(project):
        if row.get("normalized") == normalized and row.get("active") == "true":
            return row
    return None


def _scope_rows(work_dir: Path) -> list[dict]:
    return _read_csv(Path(work_dir) / "hosts" / "host_scope.csv")


def scope_decisions(work_dir: str | Path) -> list[dict]:
    """Active conversion decisions, read-only, for a host rebuild (takes the project's ``csa-work`` folder)."""
    return [r for r in _scope_rows(Path(work_dir)) if r.get("active") == "true" and SCOPE_ID.fullmatch(r.get("decision_id", ""))]


def _hash(*parts: object) -> str:
    import hashlib
    return hashlib.sha256(json.dumps(parts, sort_keys=True, ensure_ascii=False).encode("utf-8")).hexdigest()[:16]


def scope_plan(project: str | Path, device_id: str, *, host_name: str, source: str, operator: str) -> dict:
    """Read-only preview of making a connected device an application host. Writes nothing.

    ``status`` is READY only when nothing blocks it; ``problems`` lists every reason otherwise. Blocks: no
    cited source or operator; a name that is not a valid host name; a device that is retired, disputed or
    has no active IP alias; a host of that name, or one that already owns any of the addresses, in the
    generated host register (a captured, inventory or peer entry: scope is never silently overwritten); an
    active conversion decision for the device or the host name. ``preview_id`` binds the plan to the device
    revision and to the register as read, so an apply after anything changed is refused."""
    project = _project(project)
    work = _work_dir(project)
    problems: list[str] = []
    device = None
    try:
        device = get_device(project, device_id, include_retired=True)
        if device.get("active") != "true":
            problems.append(f"{device_id} is retired; restore it first")
    except ValueError as exc:
        problems.append(str(exc))
    host = str(host_name or "").strip().upper()
    source, operator = str(source or "").strip(), str(operator or "").strip()
    if not HOST_NAME.fullmatch(host):
        problems.append(f"{host_name!r} is not a usable host name (letters, digits and hyphens, 3-31 characters, starting with a letter)")
    if not source:
        problems.append("a source that identifies the device as an application host is required")
    if not operator:
        problems.append("the operator making the decision must be named")
    ips: list[str] = []
    if device is not None:
        if device.get("identification_state") == "disputed":
            problems.append(f"{device_id} is disputed; resolve the identification first")
        ips = sorted({r["normalized"] for r in _address_rows(project)
                      if r.get("device_id") == device_id and r.get("active") == "true"
                      and _address_type(r.get("normalized", "")) != "fqdn"})
        if not ips:
            problems.append(f"{device_id} has no active IP address alias to give the host")
    register = _read_csv(work / "hosts" / "hosts.csv")
    for r in register:
        name = (r.get("host") or "").strip().upper()
        owned = {x.strip() for x in (r.get("ips") or "").split(";") if x.strip()}
        if name == host:
            problems.append(f"{host} is already in the host register (in_scope: {r.get('in_scope') or 'not recorded'}); "
                            "it is not converted over an existing host")
        for ip in ips:
            if ip in owned and name != host:
                problems.append(f"{ip} is already owned by register host {name}")
    for r in scope_decisions(work):
        if r.get("device_id") == device_id:
            problems.append(f"{device_id} already has an active conversion decision ({r['decision_id']}, host {r['host']})")
        elif r.get("host", "").upper() == host:
            problems.append(f"host name {host} is already taken by conversion decision {r['decision_id']}")
    plan = {
        "status": "BLOCKED" if problems else "READY", "device_id": device_id,
        "revision": (device or {}).get("revision", ""), "host": host, "ips": ips, "source": source, "operator": operator,
        "role": (device or {}).get("role") or (device or {}).get("device_type", ""),
        "site": (device or {}).get("site_zone", ""),
        "problems": list(dict.fromkeys(problems)),
        "will_write": ["hosts/host_scope.csv", "hosts/device-audit.jsonl"],
        "unchanged": ["hosts/hosts.csv", "connected_devices.csv", "device_addresses.csv", "captures", "evidence-matrix.csv", "graph"],
        "after_rebuild": f"`csa hosts build` registers {host} as an in-scope application host with {', '.join(ips) or 'no addresses'}; "
                         "the device and its aliases stay in the register, so the conversion can be reversed",
    }
    plan["preview_id"] = _hash(device_id, plan["revision"], host, ips, source, operator,
                               _hash([sorted(r.items()) for r in register]), _hash([sorted(r.items()) for r in _scope_rows(work)]))
    return plan


def convert_to_host(project: str | Path, device_id: str, *, host_name: str, source: str, operator: str,
                    preview_id: str, expected_revision: str | int) -> dict:
    """Record the decision that a device is an application host. Needs the ``preview_id`` of a READY
    ``scope_plan`` still current for the same device revision; it appends to ``host_scope.csv`` and the
    audit log only, so the device, its aliases and every generated file are left as they are."""
    project = _project(project)
    lock = _lock(project)
    try:
        plan = scope_plan(project, device_id, host_name=host_name, source=source, operator=operator)
        if str(plan["revision"]) != str(expected_revision):
            raise ValueError(f"stale revision: expected {expected_revision}, current {plan['revision']}")
        if plan["status"] != "READY":
            raise ValueError("blocked: " + "; ".join(plan["problems"]))
        if plan["preview_id"] != str(preview_id or ""):
            raise ValueError("stale preview: the plan changed since it was previewed; preview it again")
        rows = _scope_rows(_work_dir(project))
        top = max([int(r["decision_id"][3:]) for r in rows if SCOPE_ID.fullmatch(r.get("decision_id", ""))] or [0])
        new = {"decision_id": f"HS-{top + 1:06d}", "device_id": device_id, "host": plan["host"],
               "ips": ";".join(plan["ips"]), "system": "", "role": plan["role"], "site": plan["site"],
               "source": plan["source"], "operator": plan["operator"], "decided": _utc(), "active": "true",
               "reversed_on": "", "reversed_by": "", "reverse_reason": ""}
        rows.append(new)
        _write_csv(_scope_file(project), SCOPE_FIELDS, rows)
        _append_audit(project, "scope_convert", device_id, None, new)
        return _ok(decision=new, rebuild_required=True,
                   message="Recorded. Run `csa hosts build` to register the host; nothing else was changed.")
    finally:
        _unlock(lock)


def reverse_conversion(project: str | Path, device_id: str, *, operator: str, reason: str) -> dict:
    """Undo the active conversion of a device: the decision stays in the file (active=false) with who, when and why."""
    project = _project(project)
    operator, reason = str(operator or "").strip(), str(reason or "").strip()
    if not operator or not reason:
        raise ValueError("the operator and a reason are required to reverse a conversion")
    lock = _lock(project)
    try:
        rows = _scope_rows(_work_dir(project))
        target = next((r for r in rows if r.get("device_id") == device_id and r.get("active") == "true"), None)
        if target is None:
            raise ValueError(f"unknown conversion: {device_id} has no active host conversion")
        before = dict(target)
        target.update(active="false", reversed_on=_utc(), reversed_by=operator, reverse_reason=_check_length("reason", reason))
        _write_csv(_scope_file(project), SCOPE_FIELDS, rows)
        _append_audit(project, "scope_reverse", device_id, before, dict(target))
        return _ok(decision=target, rebuild_required=True,
                   message="Reversed. Run `csa hosts build` to take the host out of the register.")
    finally:
        _unlock(lock)


IMPORT_SOURCE = "hosts/endpoints.csv (reviewed label)"


def import_endpoints_plan(project: str | Path) -> dict:
    """Dry run: which reviewed ``endpoints.csv`` rows could become connected devices. Writes nothing.

    A row is READY only when it is reviewed (reviewed=yes), its ``end`` is an exact IP or FQDN, it has a
    name and a basis, no register host owns the address or carries the name, and no existing device
    claims the address with another name. Everything else is listed under ``review`` with the reason and is
    never guessed at: ``host_owned``, ``uncited``, ``no_name``, ``not_an_address`` (a bare host name),
    ``conflict`` (another device claims the address, or two reviewed rows disagree) and ``ambiguous`` (the
    address is claimed by more than one device). Rows a device already carries under the same name are
    ``already_imported``; unreviewed rows are only counted."""
    project = _project(project)
    work = _work_dir(project)
    reviewed_rows, unreviewed = [], 0
    for r in _read_csv(work / "hosts" / "endpoints.csv"):
        if not (r.get("end") or "").strip():
            continue
        if (r.get("reviewed") or "").strip().lower() in ("yes", "y"):
            reviewed_rows.append(r)
        else:
            unreviewed += 1
    owned: dict[str, str] = {}
    for h in _read_csv(work / "hosts" / "hosts.csv"):
        name = (h.get("host") or "").strip().upper()
        if name:
            owned[name.lower()] = h.get("in_scope") or "not recorded"
        for ip in (h.get("ips") or "").split(";"):
            if ip.strip():
                owned[ip.strip().lower()] = f"{name} ({h.get('in_scope') or 'not recorded'})"
    devices = {r["device_id"]: r for r in _device_rows(project) if r.get("active") == "true"}
    claims: dict[str, set[str]] = {}
    for a in _address_rows(project):
        if a.get("active") == "true" and a.get("device_id") in devices:
            claims.setdefault(a["normalized"], set()).add(a["device_id"])
    by_address: dict[str, list[dict]] = {}
    out_ready, review, imported = [], [], []

    def problem(r: dict, kind: str, why: str) -> None:
        review.append({"end": r["end"].strip(), "name": (r.get("name") or "").strip(), "problem": kind, "detail": why})

    for r in reviewed_rows:
        end = r["end"].strip()
        try:
            n = _normalize_address(end)
        except ValueError:
            problem(r, "not_an_address", "the end is a host name or label, not an exact IP address or FQDN; "
                                        "host names belong to the host register")
            continue
        by_address.setdefault(n, []).append(r)
    for n, rows in sorted(by_address.items()):
        names = {(r.get("name") or "").strip().lower() for r in rows if (r.get("name") or "").strip()}
        r = rows[0]
        if len(names) > 1:
            problem(r, "conflict", f"{len(rows)} reviewed rows name {n} differently: "
                                   + "; ".join(sorted((x.get("name") or "").strip() for x in rows)))
            continue
        name = (r.get("name") or "").strip()
        basis = "; ".join(x for x in dict.fromkeys((x.get("basis") or "").strip() for x in rows) if x)
        evidence = ";".join(sorted({e for x in rows for e in (x.get("evidence") or "").split(";") if e.strip()}))
        if n in owned or (name.lower() in owned):
            problem(r, "host_owned", f"{n if n in owned else name} belongs to register host {owned.get(n) or owned.get(name.lower())}; "
                                     "an application host or peer is not a connected device")
            continue
        if not name:
            problem(r, "no_name", "the reviewed row has no name")
            continue
        if not basis:
            problem(r, "uncited", "the reviewed row has no source or basis")
            continue
        owners = sorted(claims.get(n, set()))
        if len(owners) > 1:
            problem(r, "ambiguous", f"{n} is claimed by {', '.join(owners)}")
            continue
        if owners:
            if devices[owners[0]].get("name", "").strip().lower() == name.lower():
                imported.append({"end": n, "name": name, "device_id": owners[0]})
            else:
                problem(r, "conflict", f"{owners[0]} already claims {n} as {devices[owners[0]].get('name')!r}; the label says {name!r}")
            continue
        out_ready.append({"address": n, "name": name, "zone": (r.get("zone") or "").strip(), "basis": basis,
                          "evidence": evidence, "provenance": f"imported from {IMPORT_SOURCE}: {basis}"
                                                              + (f"; evidence {evidence}" if evidence else "")})
    plan = {"status": "READY" if out_ready else "NOTHING_TO_IMPORT", "ready": out_ready, "review": review,
            "already_imported": imported, "ignored_unreviewed": unreviewed,
            "counts": {"ready": len(out_ready), "review": len(review), "already_imported": len(imported), "unreviewed": unreviewed},
            "will_write": ["hosts/connected_devices.csv", "hosts/device_addresses.csv", "hosts/device-audit.jsonl"],
            "unchanged": ["hosts/endpoints.csv", "hosts/hosts.csv", "captures", "evidence-matrix.csv", "graph"],
            "note": "Imported devices are `proposed`: confirm each one in the Evidence Browser before it labels a peer."}
    plan["plan_id"] = _hash(out_ready, [sorted(d.items()) for d in map(devices.get, sorted(devices))],
                            sorted((k, sorted(v)) for k, v in claims.items()))
    return plan


def import_endpoints_apply(project: str | Path, *, operator: str, plan_id: str) -> dict:
    """Create one proposed device (with its alias) for each READY row of a still-current plan.

    Needs the ``plan_id`` of a dry run, so only what was previewed is created. Idempotent: a second run
    finds every row ``already_imported`` and creates nothing. Writes the register files (with backups) and
    the audit log; ``endpoints.csv``, captures, the matrix and the graph are not touched."""
    project = _project(project)
    operator = str(operator or "").strip()
    if not operator:
        raise ValueError("the operator importing the labels must be named")
    lock = _lock(project)
    try:
        plan = import_endpoints_plan(project)
        if plan["plan_id"] != str(plan_id or ""):
            raise ValueError("stale preview: the register or endpoints changed since the dry run; run the dry run again")
        if not plan["ready"]:
            return _ok(created=[], skipped=plan["counts"], message="Nothing to import.")
        rows, araws = _device_rows(project), _address_rows(project)
        created, now = [], _utc()
        for item in plan["ready"]:
            dev = {f: "" for f in DEVICE_FIELDS}
            dev.update(device_id=_next_device_id(rows), name=_check_length("name", item["name"]),
                       site_zone=_check_length("site_zone", item["zone"]), classification="unknown",
                       identification_state="proposed", provenance=_check_length("provenance", item["provenance"]),
                       reviewer=_check_length("reviewer", operator), recorded=now, active="true", revision="1")
            alias = {"device_id": dev["device_id"], "address": item["address"], "normalized": item["address"],
                     "address_type": _address_type(item["address"]), "first_seen": "", "last_seen": "",
                     "source": IMPORT_SOURCE, "active": "true"}
            rows.append(dev)
            araws.append(alias)
            created.append({"device_id": dev["device_id"], "address": item["address"], "name": dev["name"]})
            _append_audit(project, "import_endpoint", dev["device_id"], None, dev,
                          addresses_before=None, addresses_after=[alias])
        _write_csv(_device_file(project), DEVICE_FIELDS, rows)
        _write_csv(_address_file(project), ADDRESS_FIELDS, araws)
        return _ok(created=created, skipped=plan["counts"],
                   message=f"Created {len(created)} proposed device(s). Confirm each one before it labels a peer.")
    finally:
        _unlock(lock)


def resolution_map(work_dir: str | Path) -> dict:
    """Read-only view of the register for a host rebuild: which observed IP addresses a confirmed device owns.

    Takes the project's ``csa-work`` folder and writes nothing. Only an active device whose
    identification is ``confirmed`` resolves an address, and only through an active IP alias.
    An alias claimed by more than one active device is ``ambiguous`` and resolves to no one.
    Proposed, disputed and unidentified devices are ``unresolved``: the address stays unidentified.
    Retired devices and retired aliases are ignored (an address may be reused by another device).
    Matching is exact on the normalised address; nothing is inferred from subnets or names."""
    hosts = Path(work_dir) / "hosts"
    devices = {r["device_id"]: r for r in _read_csv(hosts / "connected_devices.csv")
               if r.get("active") == "true" and DEVICE_ID.fullmatch(r.get("device_id", ""))}
    claims: dict[str, list[dict]] = {}
    for row in _read_csv(hosts / "device_addresses.csv"):
        if row.get("active") != "true" or row.get("device_id") not in devices:
            continue
        if _address_type(row.get("normalized", "")) == "fqdn":
            continue                              # a name cannot resolve an observed address
        claims.setdefault(row.get("normalized", ""), []).append(row)
    out: dict = {"confirmed": {}, "ambiguous": {}, "unresolved": {},
                 "present": (hosts / "connected_devices.csv").is_file() or (hosts / "device_addresses.csv").is_file()}
    for address, rows in sorted(claims.items()):
        ids = sorted({r["device_id"] for r in rows})
        if len(ids) > 1:
            out["ambiguous"][address] = ids
            continue
        device, alias = devices[ids[0]], rows[0]
        record = {"device_id": ids[0], "name": device.get("name", ""), "device_type": device.get("device_type", ""),
                  "role": device.get("role", ""), "owner": device.get("owner", ""), "site_zone": device.get("site_zone", ""),
                  "classification": device.get("classification", ""),
                  "identification_state": device.get("identification_state", ""),
                  "revision": device.get("revision", ""), "provenance": device.get("provenance", ""),
                  "alias": alias.get("address", ""), "alias_source": alias.get("source", "")}
        bucket = "confirmed" if device.get("identification_state") == "confirmed" else "unresolved"
        out[bucket][address] = record
    return out


def verify(project: str | Path) -> dict:
    """Consistency report for the register: duplicate active aliases, orphaned rows, bad revisions."""
    project = _project(project)
    rows = _device_rows(project)
    araws = _address_rows(project)
    ids = {r.get("device_id") for r in rows}
    problems: list[str] = []
    seen: dict[str, list[str]] = {}
    for row in araws:
        if row.get("active") != "true":
            continue
        seen.setdefault(row.get("normalized", ""), []).append(row.get("device_id", ""))
    for normalized, owners in sorted(seen.items()):
        if len(owners) > 1:
            problems.append(f"active alias {normalized!r} claimed by {sorted(owners)}")
    for row in araws:
        if row.get("device_id") not in ids:
            problems.append(f"address row references unknown device {row.get('device_id')!r}")
    status = "OK" if not problems else "ERROR"
    return {"status": status, "devices": len(rows), "addresses": len(araws), "problems": problems}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("list")
    s.add_argument("project")
    s.add_argument("--retired", action="store_true")
    s = sub.add_parser("show")
    s.add_argument("project")
    s.add_argument("device_id")
    s = sub.add_parser("create")
    s.add_argument("project")
    s.add_argument("--name", required=True)
    s.add_argument("--address", action="append", default=[])
    s = sub.add_parser("verify")
    s.add_argument("project")
    s = sub.add_parser("import-endpoints", help="dry run of importing reviewed endpoints.csv labels; --apply creates them")
    s.add_argument("project")
    s.add_argument("--apply", action="store_true")
    s.add_argument("--plan-id", default="", help="the plan_id the dry run printed (required with --apply)")
    s.add_argument("--operator", default="")
    a = ap.parse_args(argv)
    if a.cmd == "list":
        print(json.dumps(list_devices(a.project, include_retired=a.retired), indent=1))
    elif a.cmd == "show":
        print(json.dumps(get_device(a.project, a.device_id, include_retired=True), indent=1))
    elif a.cmd == "create":
        print(json.dumps(create_device(a.project, name=a.name, addresses=a.address or None), indent=1))
    elif a.cmd == "verify":
        print(json.dumps(verify(a.project), indent=1))
    elif a.cmd == "import-endpoints":
        if a.apply:
            print(json.dumps(import_endpoints_apply(a.project, operator=a.operator, plan_id=a.plan_id), indent=1))
        else:
            print(json.dumps(import_endpoints_plan(a.project), indent=1))
    return 0


